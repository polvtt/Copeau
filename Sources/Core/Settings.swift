/// Raccourci clavier : code de touche virtuel + modificateurs Cocoa.
struct Shortcut: Codable, Equatable {
    var keyCode: UInt32
    var modifiers: UInt          // NSEvent.ModifierFlags.rawValue (⌘ ⌥ ⌃ ⇧ seulement)

    static let `default` = Shortcut(keyCode: UInt32(kVK_ANSI_V), modifiers: NSEvent.ModifierFlags([.command, .shift]).rawValue)

    var flags: NSEvent.ModifierFlags { NSEvent.ModifierFlags(rawValue: modifiers).intersection([.command, .option, .control, .shift]) }

    var carbonModifiers: UInt32 {
        var m: UInt32 = 0
        if flags.contains(.command) { m |= UInt32(cmdKey) }
        if flags.contains(.option) { m |= UInt32(optionKey) }
        if flags.contains(.control) { m |= UInt32(controlKey) }
        if flags.contains(.shift) { m |= UInt32(shiftKey) }
        return m
    }

    var display: String {
        var s = ""
        if flags.contains(.control) { s += "⌃" }
        if flags.contains(.option) { s += "⌥" }
        if flags.contains(.shift) { s += "⇧" }
        if flags.contains(.command) { s += "⌘" }
        return s + KeyNames.name(for: keyCode)
    }
}

enum KeyNames {
    static let special: [Int: String] = [
        kVK_Return: "↩", kVK_Tab: "⇥", kVK_Space: "Espace", kVK_Delete: "⌫", kVK_Escape: "⎋",
        kVK_ForwardDelete: "⌦", kVK_LeftArrow: "←", kVK_RightArrow: "→", kVK_UpArrow: "↑", kVK_DownArrow: "↓",
        kVK_Home: "↖", kVK_End: "↘", kVK_PageUp: "⇞", kVK_PageDown: "⇟",
        kVK_F1: "F1", kVK_F2: "F2", kVK_F3: "F3", kVK_F4: "F4", kVK_F5: "F5", kVK_F6: "F6",
        kVK_F7: "F7", kVK_F8: "F8", kVK_F9: "F9", kVK_F10: "F10", kVK_F11: "F11", kVK_F12: "F12",
    ]

    /// Nom de la touche dans la disposition clavier courante (AZERTY : la touche de « A » de QWERTY s'affiche « Q »).
    static func name(for keyCode: UInt32) -> String {
        if let s = special[Int(keyCode)] { return s }
        return KeyboardLayout.character(for: UInt16(keyCode))?.uppercased() ?? "#\(keyCode)"
    }
}

/// Correspondance caractère ⇄ code de touche selon la disposition clavier active.
enum KeyboardLayout {
    static func character(for keyCode: UInt16, asciiCapable: Bool = false) -> String? {
        let current = asciiCapable ? nil : TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue()
        guard let src = current ?? TISCopyCurrentASCIICapableKeyboardLayoutInputSource()?.takeRetainedValue(),
              let ptr = TISGetInputSourceProperty(src, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(ptr).takeUnretainedValue() as Data
        return data.withUnsafeBytes { raw -> String? in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            var dead: UInt32 = 0
            var chars = [UniChar](repeating: 0, count: 4)
            var len = 0
            let st = UCKeyTranslate(layout, keyCode, UInt16(kUCKeyActionDisplay), 0, UInt32(LMGetKbdType()),
                                    OptionBits(kUCKeyTranslateNoDeadKeysBit), &dead, chars.count, &len, &chars)
            guard st == noErr, len > 0 else { return nil }
            return String(utf16CodeUnits: chars, count: len)
        }
    }

    /// Code de touche qui produit `char` dans la disposition ASCII courante (« v » pour ⌘V, y compris en Dvorak).
    static func keyCode(for char: Character) -> CGKeyCode? {
        let target = String(char).lowercased()
        for code in UInt16(0)..<128 where character(for: code, asciiCapable: true)?.lowercased() == target { return CGKeyCode(code) }
        return nil
    }
}

enum Retention: Int, CaseIterable, Identifiable {
    case day = 1, week = 7, month = 31, year = 365, forever = 0
    var id: Int { rawValue }
    var label: String {
        switch self {
        case .day: "1 jour"
        case .week: "1 semaine"
        case .month: "1 mois"
        case .year: "1 an"
        case .forever: "Illimitée"
        }
    }
    var limitDate: Date? { self == .forever ? nil : Date().addingTimeInterval(-Double(rawValue) * 86_400) }
}

/// Réglages persistés dans les préférences de l'app.
@MainActor
final class Settings: ObservableObject {
    private let d = UserDefaults.standard

    static let defaultIgnoredApps = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.agilebits.onepassword7", "com.1password.1password",
        "com.agilebits.onepassword-osx", "com.lastpass.LastPass", "com.dashlane.Dashlane", "com.bitwarden.desktop",
        "in.sinew.Enpass-Desktop", "com.apple.ScreenSharing",
    ]

    /// Conventions de nspasteboard.org : contenu sensible ou éphémère que les gestionnaires ne doivent pas garder.
    static let bannedTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
        "com.agilebits.onepassword", "net.antelle.keeweb",
    ]

    @Published var shortcut: Shortcut { didSet { d.set(try? JSONEncoder().encode(shortcut), forKey: "shortcut") } }
    @Published var retention: Retention { didSet { d.set(retention.rawValue, forKey: "retention") } }
    @Published var directPaste: Bool { didSet { d.set(directPaste, forKey: "directPaste") } }
    @Published var plainTextByDefault: Bool { didSet { d.set(plainTextByDefault, forKey: "plainTextByDefault") } }
    @Published var soundEffects: Bool { didSet { d.set(soundEffects, forKey: "soundEffects") } }
    @Published var linkPreviews: Bool { didSet { d.set(linkPreviews, forKey: "linkPreviews") } }
    @Published var hideDuringScreenSharing: Bool { didSet { d.set(hideDuringScreenSharing, forKey: "hideDuringScreenSharing") } }
    @Published var ignoredApps: [String] { didSet { d.set(ignoredApps, forKey: "ignoredApps") } }
    @Published var ignoredTypes: [String] { didSet { d.set(ignoredTypes, forKey: "ignoredTypes") } }
    @Published var panelHeight: Double { didSet { d.set(panelHeight, forKey: "panelHeight") } }
    @Published var lastTab: String? { didSet { d.set(lastTab, forKey: "lastTab") } }

    init() {
        shortcut = (d.data(forKey: "shortcut")).flatMap { try? JSONDecoder().decode(Shortcut.self, from: $0) } ?? .default
        retention = Retention(rawValue: d.object(forKey: "retention") as? Int ?? Retention.month.rawValue) ?? .month
        directPaste = d.object(forKey: "directPaste") as? Bool ?? true
        plainTextByDefault = d.bool(forKey: "plainTextByDefault")
        soundEffects = d.bool(forKey: "soundEffects")
        linkPreviews = d.bool(forKey: "linkPreviews")
        hideDuringScreenSharing = d.object(forKey: "hideDuringScreenSharing") as? Bool ?? true
        ignoredApps = d.stringArray(forKey: "ignoredApps") ?? Self.defaultIgnoredApps
        ignoredTypes = d.stringArray(forKey: "ignoredTypes") ?? []
        panelHeight = d.object(forKey: "panelHeight") as? Double ?? 330
        lastTab = d.string(forKey: "lastTab")
    }

    var allBannedTypes: Set<String> { Self.bannedTypes.union(ignoredTypes) }
}
